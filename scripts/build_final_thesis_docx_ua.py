    conclusions(doc)
    references(doc)
    appendices(doc)
    doc.save(OUT_DOCX)
    REFERENCE_JSON.parent.mkdir(parents=True, exist_ok=True)
    REFERENCE_JSON.write_text(
        json.dumps(
            {
                "generated_for": OUT_DOCX.name,
                "date": "2026-06-05",
                "language": "Ukrainian final thesis",
                "references_policy": "English-language sources only",
                "frontend": FRONTEND_URL,
                "backend": BACKEND_URL,
                "repository": REPO_URL,
                "references": [
                    {"authors": authors, "title": title, "venue": venue, "url": url}
                    for authors, title, venue, url in REFERENCES
                ],
            },
            indent=2,
            ensure_ascii=False,
        )
    )
    print(OUT_DOCX)
    print(REFERENCE_JSON)


