def add_discussion(doc: Document, focus: str, points: Sequence[tuple[str, str, str]]) -> None:
    templates = [
        "Для {focus} ключовим є принцип: {principle}. У ModelWeave це реалізовано через {implementation}. Без такого рішення {risk}. Тому архітектурна частина роботи безпосередньо пов'язана з математичною моделлю та практичною перевіркою.",
        "У контексті {focus} важливо, що {principle}. Прототип підтримує цю вимогу завдяки {implementation}. Це зменшує ризик того, що {risk}, і робить систему придатною для академічного аналізу.",
        "Ще один висновок для {focus}: {principle}. Реалізація використовує {implementation}; інакше {risk}. Таке рішення робить поведінку агентів не лише зручною, а й перевірною.",
    ]
    for index, (principle, implementation, risk) in enumerate(points):
        add_body(doc, templates[index % len(templates)].format(focus=focus, principle=principle, implementation=implementation, risk=risk))


